"""High-level classification service used by the API routers.

Wraps the GEE feature/classify helpers, converts raw pixel-count stats into
class names + hectares, and produces a thumbnail URL for map display.
"""
import ee

from app.config import get_settings
from app.gee.features import (
    class_area_stats,
    classify_aoi,
    evaluate_classifier,
    load_training_points,
)
from app import reference_data

PIXEL_SCALE_M = 10  # Sentinel-2 native resolution for the classified bands used


def run_classification(
    geometry: ee.Geometry,
    start_date: str,
    end_date: str,
    labels_source: str,
) -> dict:
    settings = get_settings()
    training_points = load_training_points(labels_source)
    classified, _classifier, training_features, feature_bands = classify_aoi(
        geometry, start_date, end_date, training_points
    )

    stats = class_area_stats(classified, geometry, scale=PIXEL_SCALE_M).getInfo()
    groups = stats.get("groups", [])

    pixel_area_m2 = PIXEL_SCALE_M * PIXEL_SCALE_M
    class_stats = []
    for g in groups:
        class_id = int(g["class"])
        class_name = (
            settings.crop_classes[class_id]
            if class_id < len(settings.crop_classes)
            else f"class_{class_id}"
        )
        area_m2 = g["sum"]
        class_stats.append(
            {
                "class_id": class_id,
                "class_name": class_name,
                "area_hectares": round(area_m2 / 10000, 2),
            }
        )

    vis_params = {
        "min": 0,
        "max": max(len(settings.crop_classes) - 1, 1),
        "palette": [
            "d9d9d9", "1a9850", "fee08b", "66bd63",
            "fc8d59", "d73027", "4575b4", "91bfdb",
        ][: len(settings.crop_classes)],
    }
    thumb_url = classified.getThumbURL(
        {
            "region": geometry,
            "dimensions": 1024,
            "format": "png",
            **vis_params,
        }
    )
    geotiff_url = _geotiff_download_url_safely(classified, geometry)

    return {
        "thumbnail_url": thumb_url,
        "geotiff_url": geotiff_url,
        "class_stats": sorted(class_stats, key=lambda c: -c["area_hectares"]),
        "accuracy": _evaluate_accuracy_safely(training_features, feature_bands, settings),
        "district_comparison": _district_comparison(class_stats),
    }


def _geotiff_download_url_safely(classified: ee.Image, geometry: ee.Geometry) -> str | None:
    """A direct-download GeoTIFF URL for the classified raster.

    Uses ee.Image.getDownloadURL the same way getThumbURL above is used --
    it returns a URL immediately, and the actual raster is generated by
    Earth Engine when that URL is fetched. This only works synchronously for
    AOIs small enough to stay under GEE's per-request pixel limit; for very
    large AOIs this would need to move to an async Export.image.toDrive /
    toCloudStorage task instead (tracked as a follow-up, not needed for the
    AOI sizes this pilot works with). Returns None rather than raising if
    the URL can't be generated, so a GeoTIFF export problem never breaks the
    rest of the classification result.
    """
    try:
        return classified.getDownloadURL(
            {
                "region": geometry,
                "scale": PIXEL_SCALE_M,
                "format": "GEO_TIFF",
                "crs": "EPSG:4326",
            }
        )
    except Exception:  # noqa: BLE001
        return None


def _district_comparison(class_stats: list[dict]) -> dict:
    """Rough plausibility check: total predicted cropped area in the AOI vs.
    Rupandehi district's entire major-cereal area (see app/reference_data.py).

    Deliberately not a per-crop comparison -- the reference number combines
    six crops district-wide, so it can only sanity-check overall scale (a
    single AOI should be a small fraction of the district, not larger than
    it), not validate individual crop-type predictions.
    """
    cropped_ha = sum(c["area_hectares"] for c in class_stats if c["class_name"] != "non_crop")
    district_ha = reference_data.RUPANDEHI_MAJOR_CEREAL_AREA_HA
    pct_of_district = (cropped_ha / district_ha * 100) if district_ha else None

    return {
        "district_name": reference_data.RUPANDEHI_DISTRICT_NAME,
        "district_major_cereal_area_ha": district_ha,
        "fiscal_year": reference_data.RUPANDEHI_FISCAL_YEAR,
        "source": reference_data.RUPANDEHI_SOURCE,
        "aoi_cropped_area_ha": round(cropped_ha, 2),
        "aoi_pct_of_district_cereal_area": (
            round(pct_of_district, 3) if pct_of_district is not None else None
        ),
        "note": (
            "Rough order-of-magnitude sanity check only, not a real validation: "
            "compares your AOI's total predicted cropped area against the entire "
            "district's major-cereal area across six combined crop types. If your "
            "AOI's predicted area is a large fraction of (or larger than) the whole "
            "district, that's a sign something is likely wrong with the classification."
        ),
    }


def _evaluate_accuracy_safely(
    training_features: ee.FeatureCollection, feature_bands: list[str], settings
) -> dict:
    """Run the held-out evaluation and translate it into a JSON-friendly dict.

    Never lets an evaluation failure (e.g. degenerate splits with the current
    tiny placeholder label set) take down the main classification request --
    worst case this returns `available: False` with a reason.
    """
    try:
        acc = evaluate_classifier(training_features, feature_bands).getInfo()
    except Exception as exc:  # noqa: BLE001
        return {"available": False, "reason": f"Evaluation could not run: {exc}"}

    train_count = int(acc.get("train_count", 0))
    test_count = int(acc.get("test_count", 0))
    if train_count < 1 or test_count < 1:
        return {
            "available": False,
            "train_count": train_count,
            "test_count": test_count,
            "reason": (
                f"Held-out split had {train_count} training and {test_count} test "
                "sample(s) -- need more labeled points per class before this is a "
                "reliable accuracy estimate (see project_plan.md section 3)."
            ),
        }

    class_order = acc.get("class_order", [])
    # GEE Array.getInfo() shapes: producersAccuracy is a column (Nx1), so each
    # row is a 1-element list; consumersAccuracy is a row (1xN).
    producers = acc.get("producers_accuracy") or []
    consumers = (acc.get("consumers_accuracy") or [[]])[0]

    per_class = []
    for idx, class_id in enumerate(class_order):
        class_name = (
            settings.crop_classes[class_id]
            if class_id < len(settings.crop_classes)
            else f"class_{class_id}"
        )
        recall = producers[idx][0] if idx < len(producers) else None
        precision = consumers[idx] if idx < len(consumers) else None
        # GEE returns 0 for classes absent from the test split rather than
        # null, which reads as "0% accurate" -- report those as unknown
        # instead, since there was nothing to test them against.
        per_class.append(
            {
                "class_name": class_name,
                "recall": round(recall, 3) if recall else None,
                "precision": round(precision, 3) if precision else None,
            }
        )

    return {
        "available": True,
        "train_count": train_count,
        "test_count": test_count,
        "overall_accuracy": round(acc["overall_accuracy"], 3),
        "kappa": round(acc["kappa"], 3),
        "per_class": per_class,
        "note": (
            "Held-out validation on a random split of the current labeled points. "
            "With only a handful of labeled polygons this is a pipeline smoke test, "
            "not a trustworthy accuracy number -- see project_plan.md section 3."
        ),
    }
